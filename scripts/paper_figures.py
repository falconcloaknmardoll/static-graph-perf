plt.close(fig)

# ── 8c arm table ───────────────────────────────────────────────────────────────────────────
def pm(x):
    return f"{np.mean(x):.4f} $\\pm$ {np.std(x, ddof=1):.4f}"


lines = [r"\begin{tabular}{lcccc}", r"\toprule",
         r"Arm & CONV slowdown & OTHER slowdown & $\Delta$ CONV & BH-$p$ \\", r"\midrule"]
